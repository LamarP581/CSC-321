class Program:
    def __init__(self, statements):
        self.statements = statements


class Assignment:
    def __init__(self, name, expr):
        self.name = name
        self.expr = expr


class Print:
    def __init__(self, expr):
        self.expr = expr


class BinaryOp:
    def __init__(self, left, op, right):
        self.left = left
        self.op = op
        self.right = right


class Integer:
    def __init__(self, value):
        self.value = value


class IdentifierNode:
    def __init__(self, name):
        self.name = name


