def run_lexer(text):
    lexer = Lexer(text)
    tokens = []

    while True:
        tok = lexer.get_next_token()
        tokens.append(tok)
        if tok.type == EOF:
            break

    for t in tokens:
        print(t)


def run_parser(text):
    lexer = Lexer(text)
    parser = Parser(lexer)
    ast = parser.parse()
    print(json.dumps(ast_to_dict(ast), indent=2))


