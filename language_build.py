class Token:
    def __init__(self, type_, value):
        self.type = type_
        self.value = value

    def __repr__(self):
        return f"{self.type}({self.value})"


# Token Types
INTEGER = "INTEGER"
IDENTIFIER = "IDENTIFIER"
PLUS = "PLUS"
MINUS = "MINUS"
STAR = "STAR"
SLASH = "SLASH"
EQUAL = "EQUAL"
SEMICOLON = "SEMICOLON"
LPAREN = "LPAREN"
RPAREN = "RPAREN"
PRINT = "PRINT"
EOF = "EOF"


